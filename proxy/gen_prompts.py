"""Regenerate proxy/src/prompts.js from summarizer.py so the server and the app share one prompt.
Run after editing SYSTEM_PROMPT or JSON_SPEC:  python3 proxy/gen_prompts.py"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
import summarizer  # noqa: E402

out = root / "proxy" / "src" / "prompts.js"
out.write_text("// Generated by proxy/gen_prompts.py from summarizer.py. Do not edit by hand.\n"
               f"export const SYSTEM_PROMPT = {json.dumps(summarizer.SYSTEM_PROMPT)};\n"
               f"export const JSON_SPEC = {json.dumps(summarizer.JSON_SPEC)};\n")
print("wrote", out)
